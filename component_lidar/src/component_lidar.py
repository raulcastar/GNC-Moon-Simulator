"""
ROS 2 Lifecycle Node for Unreal Engine Velodyne VLP-16 LiDAR Integration.

This module provides a robust, asynchronous UDP bridging interface for simulated 
Velodyne VLP-16 LiDAR data generated by Unreal Engine. It captures raw binary 
datagrams, decodes the proprietary Velodyne packet structure into 3D Cartesian 
coordinates, and publishes standard sensor_msgs/PointCloud2 messages.

Architecture:
    - Inherits from rclpy.lifecycle.Node for managed state transitions.
    - Utilizes a daemonized background thread for blocking I/O (UDP socket) 
      to prevent starving the main ROS 2 executor.
    - Implements automatic socket recovery to handle OS-level network drops.

Author: [Your Name/Company]
License: MIT
"""

import socket
import struct
import math
import threading
import time
from typing import Optional, Tuple
import numpy as np

import rclpy
import rclpy.lifecycle
from rclpy.lifecycle import Publisher, State, TransitionCallbackReturn

from sensor_msgs.msg import PointCloud2, PointField
from std_msgs.msg import Header
from sensor_msgs_py import point_cloud2


# =============================================================================
# Pre-computed Hardware Constants
# =============================================================================
# The VLP-16 has 16 laser channels spread across a 30-degree vertical field of view.
# These angles range from -15 degrees to +15 degrees.
# Pre-computing trigonometric arrays saves ~300,000 math operations per second.
VLP16_ELEVATIONS_RAD = np.radians([-15, 1, -13, 3, -11, 5, -9, 7, -7, 9, -5, 11, -3, 13, -1, 15])
COS_ELE = np.cos(VLP16_ELEVATIONS_RAD)
SIN_ELE = np.sin(VLP16_ELEVATIONS_RAD)


class LifecycleUnrealLidarOnly(rclpy.lifecycle.Node):
    """
    Lifecycle-managed ROS 2 node for high-frequency LiDAR UDP ingestion.

    Attributes:
        _pub_pointcloud (Publisher): Lifecycle publisher for PointCloud2 messages.
        _udp_sock (socket.socket): The UDP socket listening for Unreal Engine data.
        _lidar_thread (threading.Thread): Background thread handling the blocking socket.
        _is_lidar_running (bool): Thread synchronization flag.
        _point_buffer (list): Accumulator for parsed XYZI coordinates.
    """

    def __init__(self, node_name: str, **kwargs):
        """
        Initializes the node state and declares ROS 2 parameter interfaces.

        Args:
            node_name (str): The name assigned to the node within the ROS 2 graph.
            **kwargs: Additional keyword arguments passed to the rclpy.lifecycle.Node constructor.
        """
        super().__init__(node_name, **kwargs)
        
        self._pub_pointcloud: Optional[Publisher] = None
        self._udp_sock: Optional[socket.socket] = None
        
        self._lidar_thread: Optional[threading.Thread] = None
        self._is_lidar_running: bool = False
        self._point_buffer: list = []

        self.declare_parameters(
            namespace='',
            parameters=[
                ('lidar_ip', rclpy.Parameter.Type.STRING),
                ('lidar_port', rclpy.Parameter.Type.INTEGER),
            ])

    # -------------------------------------------------------------------------
    # Hardware & Network Layer
    # -------------------------------------------------------------------------

    def _bind_socket(self) -> bool:
        """
        Safely creates and binds the UDP listening socket.
        
        If an existing socket is detected (e.g., during a recovery sequence), 
        it is closed prior to reallocation to prevent Address In Use (EADDRINUSE) errors.
        
        Returns:
            bool: True if the socket successfully bound to the interface, False otherwise.
        """
        try:
            if self._udp_sock:
                self._udp_sock.close()
                
            self._udp_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            self._udp_sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            
            # A 1.0s timeout ensures the recvfrom() call doesn't block indefinitely,
            # allowing the thread to periodically check the _is_lidar_running termination flag.
            self._udp_sock.settimeout(1.0) 
            self._udp_sock.bind((self.lidar_ip, self.lidar_port))
            
            self.get_logger().info(f"UDP Socket bound to {self.lidar_ip}:{self.lidar_port}")
            return True
            
        except Exception as e:
            self.get_logger().error(f"Hardware binding failure on {self.lidar_ip}:{self.lidar_port} -> {e}")
            return False

    # -------------------------------------------------------------------------
    # Threading & Data Pipeline
    # -------------------------------------------------------------------------

    def _lidar_listen_loop(self) -> None:
        """
        Main execution loop for the background daemon thread.
        
        Continuously polls the UDP socket, enforces the Velodyne packet footprint, 
        and handles OS-level network fault recovery.
        """
        self.get_logger().info("Data ingestion thread active. Awaiting packets...")
        
        while self._is_lidar_running:
            try:
                data, addr = self._udp_sock.recvfrom(2048)
                
                # Strict packet validation: VLP-16 packets must be exactly 1206 bytes.
                # (42 byte header + 12x 100-byte data blocks + 4 byte timestamp + 2 byte factory)
                if len(data) != 1206:
                    continue
                
                self._parse_velodyne_packet(data)
                
                # Accumulate points to mimic a physical LiDAR sweep.
                # 30,000 points equates to roughly one 360-degree rotation at 600 RPM.
                if len(self._point_buffer) >= 30000:
                    self._publish_pointcloud()

            except socket.timeout:
                # Expected behavior: socket timed out to allow checking the while loop condition
                continue
                
            except OSError as e:
                # Handles critical faults like virtual network interfaces dropping
                if self._is_lidar_running:
                    self.get_logger().warn(f"Network interface fault ({e}). Initiating auto-recovery...")
                    time.sleep(2.0)
                    self._bind_socket()
                    
            except Exception as e:
                if self._is_lidar_running:
                    self.get_logger().error(f"Unhandled exception in parsing pipeline: {e}")

    def _parse_velodyne_packet(self, data: bytes) -> None:
        """
        Decodes a binary VLP-16 packet and transforms spherical coordinates to Cartesian.
        
        Args:
            data (bytes): The 1206-byte binary payload.
        """
        # Iterate over the 12 data blocks (100 bytes each)
        for i in range(12):
            offset = i * 100
            
            # Unpack the 2-byte sync flag and 2-byte Azimuth angle
            # Format '<HH' = Little-Endian, Unsigned Short (2 bytes), Unsigned Short (2 bytes)
            flag, azimuth_raw = struct.unpack_from('<HH', data, offset)
            
            # The Sync Flag for Velodyne is 0xFFEE.
            # In little-endian integer format, 0xEEFF equals 61183.
            if flag != 61183: 
                continue 
                
            # Velodyne azimuth is provided in hundredths of a degree (e.g., 35999 = 359.99 deg)
            azimuth = math.radians(azimuth_raw / 100.0)
            cos_az = math.cos(azimuth)
            sin_az = math.sin(azimuth)

            # Each data block contains 32 individual laser firings
            for j in range(32):
                laser_id = j % 16
                
                # Unpack 2-byte distance and 1-byte intensity
                # Format '<HB' = Little-Endian, Unsigned Short (2 bytes), Unsigned Char (1 byte)
                dist_raw, intensity = struct.unpack_from('<HB', data, offset + 4 + j * 3)
                
                # A distance of 0 indicates the laser fired into the sky or out of bounds
                if dist_raw == 0:
                    continue
                    
                # VLP-16 hardware resolution is mapped at 2mm (0.002m) increments
                dist = dist_raw * 0.002
                
                # Cartesian Conversion (Spherical -> Right-Hand Rule Cartesian)
                x = dist * COS_ELE[laser_id] * cos_az
                y = dist * COS_ELE[laser_id] * sin_az * -1.0  # Invert Y to match ROS standard coordinates
                z = dist * SIN_ELE[laser_id]

                self._point_buffer.append([x, y, z, float(intensity)])

    def _publish_pointcloud(self) -> None:
        """
        Serializes the point buffer into a standardized sensor_msgs/PointCloud2 struct 
        and pushes it to the ROS 2 middleware layer.
        """
        if not self._pub_pointcloud or not self._is_lidar_running:
            return

        header = Header()
        header.stamp = self.get_clock().now().to_msg()
        header.frame_id = 'velodyne'

        # Define the memory mapping for the PointCloud2 message
        fields = [
            PointField(name='x', offset=0, datatype=PointField.FLOAT32, count=1),
            PointField(name='y', offset=4, datatype=PointField.FLOAT32, count=1),
            PointField(name='z', offset=8, datatype=PointField.FLOAT32, count=1),
            PointField(name='intensity', offset=12, datatype=PointField.FLOAT32, count=1),
        ]

        # point_cloud2.create_cloud handles the struct.pack logic internally
        pc2_msg = point_cloud2.create_cloud(header, fields, self._point_buffer)
        self._pub_pointcloud.publish(pc2_msg)
        
        # Flush the buffer memory for the next rotational sweep
        self._point_buffer.clear()

    # -------------------------------------------------------------------------
    # ROS 2 Lifecycle Management Overrides
    # -------------------------------------------------------------------------

    def on_configure(self, state: State) -> TransitionCallbackReturn:
        """
        Callback triggered during the Unconfigured -> Inactive transition.
        Resolves parameters and allocates memory/hardware resources.
        """
        self.get_logger().info("Executing Lifecycle Transition: CONFIGURED.")

        self.lidar_ip = self.get_parameter('lidar_ip').value
        self.lidar_port = self.get_parameter('lidar_port').value

        self._pub_pointcloud = self.create_lifecycle_publisher(PointCloud2, 'velodyne_points', 10)
        
        if not self._bind_socket():
            return TransitionCallbackReturn.FAILURE

        return TransitionCallbackReturn.SUCCESS

    def on_activate(self, state: State) -> TransitionCallbackReturn:
        """
        Callback triggered during the Inactive -> Active transition.
        Enables publishers and spawns the ingestion thread.
        """
        self.get_logger().info("Executing Lifecycle Transition: ACTIVE.")
        
        self._is_lidar_running = True
        self._lidar_thread = threading.Thread(target=self._lidar_listen_loop, daemon=True)
        self._lidar_thread.start()
        
        return super().on_activate(state)

    def on_deactivate(self, state: State) -> TransitionCallbackReturn:
        """
        Callback triggered during the Active -> Inactive transition.
        Halts data ingestion and safely joins active threads.
        """
        self.get_logger().info("Executing Lifecycle Transition: DEACTIVATED.")
        
        self._is_lidar_running = False
        if self._lidar_thread and self._lidar_thread.is_alive():
            self._lidar_thread.join(timeout=2.0)
            
        return super().on_deactivate(state)

    def on_cleanup(self, state: State) -> TransitionCallbackReturn:
        """
        Callback triggered during the Inactive -> Unconfigured transition.
        Purges memory, destroys publishers, and releases hardware bindings.
        """
        self.get_logger().info('Executing Lifecycle Transition: CLEANING UP.')
        
        self._is_lidar_running = False
        if self._pub_pointcloud:
            self.destroy_publisher(self._pub_pointcloud)
        if self._udp_sock:
            self._udp_sock.close()
            
        return TransitionCallbackReturn.SUCCESS

    def on_shutdown(self, state: State) -> TransitionCallbackReturn:
        """
        Callback triggered during node destruction (e.g., SIGINT).
        Ensures guaranteed release of resources.
        """
        self.get_logger().info('Executing Lifecycle Transition: SHUTTING DOWN.')
        self.on_cleanup(state)
        return TransitionCallbackReturn.SUCCESS


def main():
    """
    Executable entry point. Initializes the ROS 2 context, instantiates the node, 
    and spins the executor block.
    """
    rclpy.init()
    
    # A SingleThreadedExecutor is sufficient since blocking I/O is offloaded 
    # to a native Python threading.Thread object within the node.
    executor = rclpy.executors.SingleThreadedExecutor()
    lc_node = LifecycleUnrealLidarOnly('lc_unreal_lidar')
    executor.add_node(lc_node)
    
    try:
        executor.spin()
    except (KeyboardInterrupt, rclpy.executors.ExternalShutdownException):
        lc_node.destroy_node()

if __name__ == '__main__':
    main()